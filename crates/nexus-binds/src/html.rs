//! Standalone HTML reference card (replaces EDRefCard's image output).
//!
//! The page has no external resources: inline CSS only, no scripts, no fonts, no images. It is
//! dark on screen and switches to an ink-friendly light palette when printed.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use rustc_hash::{FxHashMap, FxHashSet};

use crate::analysis::{Importance, Report};
use crate::bindings::{ActionBinding, Bindings, Slot};
use crate::catalogue::{Category, Context, action_info, catalogue_order};
use crate::input::{DeviceKind, Input, device_name, device_short_name, key_label};
use crate::util::{escape_html as esc, humanize, natural_cmp};

/// Rendering switches for [`render_html_with`].
#[derive(Debug, Clone)]
pub struct RenderOptions {
    /// Also list actions that have no binding (greyed out). Default: false.
    pub include_unbound: bool,
    /// Add the per-device section listing every used input. Default: true.
    pub by_device: bool,
    /// Page title; default `<preset> – Elite Dangerous bindings`.
    pub title: Option<String>,
}

impl Default for RenderOptions {
    fn default() -> Self {
        Self {
            include_unbound: false,
            by_device: true,
            title: None,
        }
    }
}

/// Renders the reference card with default options.
pub fn render_html(bindings: &Bindings, report: &Report) -> String {
    render_html_with(bindings, report, &RenderOptions::default())
}

/// Renders a standalone, printable HTML reference card: summary, issues (conflicts, unbound
/// essentials, modifier notes), devices, key settings, all bindings grouped by context and
/// category, and every used input grouped by device. Conflicting bindings are highlighted.
pub fn render_html_with(bindings: &Bindings, report: &Report, options: &RenderOptions) -> String {
    let conflicted = report.conflicted_slots();
    let mut partners: FxHashMap<(&str, Slot), Vec<String>> = FxHashMap::default();
    for c in &report.conflicts {
        for a in &c.actions {
            let others = c
                .actions
                .iter()
                .filter(|o| o.action != a.action)
                .map(|o| o.name.clone());
            partners
                .entry((a.action.as_str(), a.slot))
                .or_default()
                .extend(others);
        }
    }
    for names in partners.values_mut() {
        names.sort();
        names.dedup();
    }
    let ctx = Ctx {
        conflicted: &conflicted,
        partners: &partners,
    };

    let preset = if bindings.preset_name.is_empty() {
        "Unnamed preset"
    } else {
        bindings.preset_name.as_str()
    };
    let title = options
        .title
        .clone()
        .unwrap_or_else(|| format!("{preset} – Elite Dangerous bindings"));

    let mut out = String::with_capacity(160 * 1024);
    out.push_str("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n");
    out.push_str("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
    let _ = writeln!(out, "<title>{}</title>", esc(&title));
    let _ = writeln!(
        out,
        "<style>{CSS}</style>\n</head>\n<body>\n<div class=\"wrap\">"
    );

    header(&mut out, bindings, report, preset, options);
    out.push_str("<main>\n");
    issues(&mut out, report);
    devices(&mut out, report);
    settings(&mut out, bindings);
    contexts(&mut out, bindings, options, &ctx);
    if options.by_device {
        by_device(&mut out, bindings, report, &ctx);
    }
    out.push_str("</main>\n");
    out.push_str(
        "<footer>Generated by Elite Nexus (nexus-binds). Keys are shown as named in the bindings \
         file; with a non-US keyboard layout they may differ from the printed key caps. Action \
         names and groupings partly derived from EDRefCard by Richard Buckle (MIT licence).\
         </footer>\n</div>\n</body>\n</html>\n",
    );
    out
}

/// Conflict lookups shared by the sections.
struct Ctx<'a> {
    conflicted: &'a FxHashSet<(&'a str, Slot)>,
    partners: &'a FxHashMap<(&'a str, Slot), Vec<String>>,
}

impl Ctx<'_> {
    fn is_conflicted(&self, action: &str, slot: Slot) -> bool {
        self.conflicted.contains(&(action, slot))
    }
}

fn header(
    out: &mut String,
    bindings: &Bindings,
    report: &Report,
    preset: &str,
    options: &RenderOptions,
) {
    out.push_str(
        "<header class=\"top\">\n<div class=\"brand\">Elite Nexus · Bindings reference</div>\n",
    );
    let _ = writeln!(out, "<h1>{}</h1>", esc(preset));

    let mut meta: Vec<String> = Vec::new();
    if let Some(v) = bindings.version {
        meta.push(format!("Version <b>{v}</b>"));
    }
    if let Some(layout) = &bindings.keyboard_layout {
        meta.push(format!("Keyboard layout <b>{}</b>", esc(layout)));
    }
    meta.push(format!(
        "<b>{}</b> of {} actions bound · <b>{}</b> bindings · <b>{}</b> device{}",
        report.totals.bound_actions,
        report.totals.actions,
        report.totals.bindings,
        report.devices.len(),
        if report.devices.len() == 1 { "" } else { "s" }
    ));
    let _ = writeln!(out, "<div class=\"meta\">{}</div>", meta.join(" · "));
    if !bindings.sources.is_empty() {
        let sources: Vec<String> = bindings
            .sources
            .iter()
            .map(|(c, name)| format!("{} <b>{}</b>", c.label(), esc(name)))
            .collect();
        let _ = writeln!(
            out,
            "<div class=\"meta\">Active presets: {}</div>",
            sources.join(" · ")
        );
    }

    let essentials = report.missing_essentials().count();
    let recommended = report.missing.len() - essentials;
    out.push_str("<div class=\"tiles\">\n");
    tile(out, report.totals.bound_actions, "actions bound", "");
    tile(
        out,
        report.conflicts.len(),
        "conflicts",
        if report.conflicts.is_empty() {
            "ok"
        } else {
            "bad"
        },
    );
    tile(
        out,
        essentials,
        "essentials unbound",
        if essentials == 0 { "ok" } else { "bad" },
    );
    tile(
        out,
        recommended,
        "recommended unbound",
        if recommended == 0 { "ok" } else { "warn" },
    );
    if !report.modifier_notes.is_empty() {
        tile(out, report.modifier_notes.len(), "modifier notes", "");
    }
    out.push_str("</div>\n<nav class=\"toc\">");
    out.push_str("<a href=\"#issues\">Issues</a><a href=\"#devices\">Devices</a>");
    for context in Context::ALL {
        if bindings
            .bound_actions()
            .any(|a| a.info().context == context)
        {
            let _ = write!(
                out,
                "<a href=\"#ctx-{}\">{}</a>",
                anchor(context),
                context.label()
            );
        }
    }
    if options.by_device {
        out.push_str("<a href=\"#by-device\">By device</a>");
    }
    out.push_str("</nav>\n</header>\n");
}

fn tile(out: &mut String, value: usize, label: &str, class: &str) {
    let _ = writeln!(
        out,
        "<div class=\"tile {class}\"><b>{value}</b><span>{label}</span></div>"
    );
}

fn anchor(context: Context) -> String {
    context.label().to_ascii_lowercase().replace([' ', '-'], "")
}

fn issues(out: &mut String, report: &Report) {
    out.push_str("<section id=\"issues\">\n<h2>Issues</h2>\n<div class=\"grid wide\">\n");

    // Conflicts.
    out.push_str("<div class=\"card\"><h3>Conflicts</h3>\n");
    if report.conflicts.is_empty() {
        out.push_str("<p class=\"ok-msg\">No conflicting bindings found.</p>\n");
    } else {
        out.push_str("<table><tr><th>Input</th><th>Active in</th><th>Bound to</th></tr>\n");
        for c in &report.conflicts {
            let actions: Vec<String> = c
                .actions
                .iter()
                .map(|a| {
                    format!(
                        "{} <span class=\"ctx\">{} · {}</span>",
                        esc(&a.name),
                        a.context.label(),
                        a.slot.label()
                    )
                })
                .collect();
            let _ = writeln!(
                out,
                "<tr><td>{}</td><td>{}</td><td>{}</td></tr>",
                chip(&c.input, true, None, ""),
                c.scope.label(),
                actions.join("<br>")
            );
        }
        out.push_str("</table>\n");
    }
    out.push_str("</div>\n");

    // Unbound requirements.
    out.push_str("<div class=\"card\"><h3>Unbound essentials &amp; recommendations</h3>\n");
    if report.missing.is_empty() {
        out.push_str("<p class=\"ok-msg\">Everything on the checklist is bound.</p>\n");
    } else {
        out.push_str("<table><tr><th></th><th>Function</th><th>Bind one of</th></tr>\n");
        for m in &report.missing {
            let class = if m.importance == Importance::Essential {
                "ess"
            } else {
                "rec"
            };
            let options: Vec<String> = m.options.iter().map(|o| esc(o).into_owned()).collect();
            let _ = writeln!(
                out,
                "<tr><td><span class=\"tag {class}\">{}</span></td><td>{} <span class=\"ctx\">{}</span></td><td>{}</td></tr>",
                m.importance.label(),
                esc(m.label),
                m.context.label(),
                options.join(" <i>or</i> ")
            );
        }
        out.push_str("</table>\n");
    }
    out.push_str("</div>\n");

    // Modifier notes.
    if !report.modifier_notes.is_empty() {
        out.push_str("<div class=\"card\"><h3>Keys used as modifier and on their own</h3>\n");
        out.push_str(
            "<p class=\"hint\">Informational — the game's own presets do this too. If one press ever \
             seems to trigger two things, look here first.</p>\n\
             <table><tr><th>Key</th><th>Active in</th><th>Modifier for</th><th>Alone</th></tr>\n",
        );
        for n in &report.modifier_notes {
            let names = |ids: &[String]| -> String {
                ids.iter()
                    .map(|id| esc(&action_info(id).name).into_owned())
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            let input = Input::new(n.device.clone(), n.key.clone());
            let _ = writeln!(
                out,
                "<tr><td>{}</td><td>{}</td><td>{}</td><td>{}</td></tr>",
                chip(&input, false, None, ""),
                n.scope.label(),
                names(&n.as_modifier),
                names(&n.alone)
            );
        }
        out.push_str("</table></div>\n");
    }
    out.push_str("</div>\n</section>\n");
}

fn devices(out: &mut String, report: &Report) {
    out.push_str("<section id=\"devices\">\n<h2>Devices</h2>\n<div class=\"card\">\n");
    if report.devices.is_empty() {
        out.push_str("<p class=\"none\">Nothing is bound.</p>\n");
    } else {
        out.push_str(
            "<table class=\"num\"><tr><th>Device</th><th>Type</th><th>Buttons</th><th>Axes</th>\
             <th>Modifier uses</th><th>Inputs used</th><th>Actions</th><th>Conflicts</th></tr>\n",
        );
        for d in &report.devices {
            let raw_id = if d.device == d.name {
                String::new()
            } else {
                format!("<span class=\"ctx\">{}</span>", esc(&d.device))
            };
            let _ = writeln!(
                out,
                "<tr><td><span class=\"dot {}\"></span>{}{raw_id}</td><td>{}</td><td>{}</td><td>{}</td><td>{}</td><td>{}</td><td>{}</td><td{}>{}</td></tr>",
                kind_class(d.kind),
                esc(&d.name),
                d.kind.label(),
                d.buttons,
                d.axes,
                d.modifier_uses,
                d.inputs,
                d.actions,
                if d.conflicts > 0 {
                    " class=\"bad\""
                } else {
                    ""
                },
                d.conflicts
            );
        }
        out.push_str("</table>\n");
    }
    out.push_str(
        "<div class=\"legend\"><span><i class=\"kb\"></i>Keyboard</span><span><i class=\"ms\"></i>Mouse</span>\
         <span><i class=\"joy\"></i>Joystick / HOTAS</span><span><i class=\"pad\"></i>Gamepad</span>\
         <span><i class=\"vr\"></i>VR</span><span><i class=\"cf\"></i>Conflict</span></div>\n",
    );
    out.push_str("</div>\n</section>\n");
}

/// Settings worth showing on a reference card, with display names.
const KEY_SETTINGS: &[(&str, &str)] = &[
    ("MouseXMode", "Ship mouse X axis"),
    ("MouseYMode", "Ship mouse Y axis"),
    ("ThrottleRange", "Ship throttle range"),
    ("YawToRollMode", "Yaw into roll"),
    ("DeployHardpointsOnFire", "Deploy hardpoints on fire"),
    ("UIFocusMode", "UI focus mode"),
    ("MuteButtonMode", "Voice comms button"),
    ("HeadlookMode", "Headlook mode"),
    ("MouseHeadlook", "Mouse headlook"),
    ("DriveAssistDefault", "SRV drive assist by default"),
    ("BuggyThrottleRange", "SRV throttle range"),
    ("MouseHumanoidXMode", "On-foot mouse X axis"),
    ("MouseHumanoidYMode", "On-foot mouse Y axis"),
    ("EnableAimAssistOnFoot", "On-foot aim assist"),
];

fn settings(out: &mut String, bindings: &Bindings) {
    let rows: Vec<(&str, String)> = KEY_SETTINGS
        .iter()
        .filter_map(|(name, label)| {
            bindings
                .setting(name)
                .map(|v| (*label, pretty_setting(name, v)))
        })
        .collect();
    if rows.is_empty() {
        return;
    }
    out.push_str("<section id=\"settings\">\n<h2>Key settings</h2>\n<div class=\"card\"><div class=\"kvgrid\">\n");
    for (label, value) in rows {
        let _ = writeln!(
            out,
            "<div class=\"kv\"><span>{}</span><b>{}</b></div>",
            esc(label),
            esc(&value)
        );
    }
    out.push_str("</div></div>\n</section>\n");
}

/// `Bindings_MousePitchInverted` → `Pitch (inverted)`, `""` → `Full range` for throttle ranges.
fn pretty_setting(name: &str, value: &str) -> String {
    if value.is_empty() {
        return if name.ends_with("ThrottleRange") {
            "Full range".to_owned()
        } else {
            "Off / none".to_owned()
        };
    }
    if matches!(value, "0" | "1") {
        return if value == "1" {
            "On".to_owned()
        } else {
            "Off".to_owned()
        };
    }
    let mut v = value;
    for prefix in [
        "Bindings_YawIntoRoll",
        "Bindings_FocusMode",
        "Bindings_HeadlookMode",
        "Bindings_BuggyThrottle",
        "Bindings_Throttle",
        "Bindings_Mouse",
        "Bindings_",
        "mute_",
    ] {
        if let Some(rest) = v.strip_prefix(prefix)
            && !rest.is_empty()
        {
            v = rest;
            break;
        }
    }
    let words = humanize(v).replace("Foreward", "Forward");
    match words.strip_suffix(" Inverted") {
        Some(base) => format!("{base} (inverted)"),
        None => words,
    }
}

fn contexts(out: &mut String, bindings: &Bindings, options: &RenderOptions, ctx: &Ctx<'_>) {
    // context -> category -> actions (catalogue order)
    let mut grouped: BTreeMap<Context, BTreeMap<Category, Vec<&ActionBinding>>> = BTreeMap::new();
    for action in &bindings.actions {
        let info = action.info();
        if !action.is_bound() && (!options.include_unbound || info.legacy) {
            continue;
        }
        grouped
            .entry(info.context)
            .or_default()
            .entry(info.category)
            .or_default()
            .push(action);
    }
    for categories in grouped.values_mut() {
        for actions in categories.values_mut() {
            actions.sort_by(|a, b| {
                catalogue_order(&a.action)
                    .cmp(&catalogue_order(&b.action))
                    .then_with(|| a.action.cmp(&b.action))
            });
        }
    }

    for (context, categories) in &grouped {
        let bound: usize = categories
            .values()
            .flatten()
            .filter(|a| a.is_bound())
            .count();
        let _ = writeln!(
            out,
            "<section id=\"ctx-{}\">\n<h2>{} <span class=\"count\">{bound} bound</span></h2>\n<div class=\"grid\">",
            anchor(*context),
            context.label()
        );
        for (category, actions) in categories {
            let _ = writeln!(
                out,
                "<div class=\"card\"><h3>{}</h3><table>",
                category.label()
            );
            for action in actions {
                action_row(out, action, ctx);
            }
            out.push_str("</table></div>\n");
        }
        out.push_str("</div>\n</section>\n");
    }
}

fn action_row(out: &mut String, action: &ActionBinding, ctx: &Ctx<'_>) {
    let info = action.info();
    let any_conflict = action
        .inputs()
        .any(|(slot, _)| ctx.is_conflicted(&action.action, slot));
    let mut name = esc(&info.name).into_owned();
    if action.toggle_on == Some(true) {
        name.push_str("<span class=\"tag\">toggle</span>");
    }
    if !info.known {
        name.push_str("<span class=\"tag\" title=\"Not in the action catalogue\">?</span>");
    }
    if info.legacy {
        name.push_str(
            "<span class=\"tag\" title=\"No longer used by the current game\">legacy</span>",
        );
    }
    let class = match (any_conflict, action.is_bound()) {
        (true, _) => " class=\"c\"",
        (false, false) => " class=\"u\"",
        _ => "",
    };
    let _ = write!(
        out,
        "<tr{class}><td class=\"n\" title=\"{}\">{name}</td><td>",
        esc(&action.action)
    );
    if !action.is_bound() {
        out.push_str("<span class=\"none\">unbound</span>");
    }
    for (slot, input) in action.inputs() {
        let conflict = ctx.is_conflicted(&action.action, slot);
        let partners = ctx
            .partners
            .get(&(action.action.as_str(), slot))
            .map(Vec::as_slice);
        let mut extra = String::new();
        if let (Slot::Axis, Some(axis)) = (slot, &action.axis) {
            if axis.inverted {
                extra.push_str("<span class=\"t\">inv</span>");
            }
            if axis.deadzone > 0.0 {
                let percent = axis.deadzone * 100.0;
                let precision = if percent < 1.0 { 1 } else { 0 };
                let _ = write!(extra, "<span class=\"t\">dz {percent:.precision$}%</span>");
            }
        }
        out.push_str(&chip(input, conflict, partners, &extra));
    }
    out.push_str("</td></tr>\n");
}

fn kind_class(kind: DeviceKind) -> &'static str {
    match kind {
        DeviceKind::Keyboard => "kb",
        DeviceKind::Mouse => "ms",
        DeviceKind::Joystick => "joy",
        DeviceKind::Gamepad => "pad",
        DeviceKind::Vr => "vr",
        DeviceKind::Other => "oth",
    }
}

/// A key chip: device-coloured, red when conflicting, with a tooltip naming the device, the raw
/// key and the conflicting actions.
fn chip(input: &Input, conflict: bool, partners: Option<&[String]>, extra: &str) -> String {
    chip_labelled(input, &input.display(), conflict, partners, extra)
}

fn chip_labelled(
    input: &Input,
    label: &str,
    conflict: bool,
    partners: Option<&[String]>,
    extra: &str,
) -> String {
    let mut title = format!("{} · {}", device_name(&input.device), input.key);
    for (device, key) in &input.modifiers {
        let _ = write!(title, " + {}:{}", device, key);
    }
    if let Some(p) = partners.filter(|p| !p.is_empty()) {
        let _ = write!(title, " — conflicts with {}", p.join(", "));
    }
    format!(
        "<span class=\"k {}{}\" title=\"{}\">{}{}</span>",
        kind_class(input.device_kind()),
        if conflict { " c" } else { "" },
        esc(&title),
        esc(label),
        extra
    )
}

/// Label of an input within its device's section: like [`Input::display`] but without the
/// device's own prefix.
fn label_on_device(input: &Input) -> String {
    let mut parts: Vec<String> = Vec::with_capacity(input.modifiers.len() + 1);
    for (device, key) in &input.modifiers {
        let label = key_label(key);
        if device == &input.device || matches!(device.as_str(), "Keyboard" | "Mouse") {
            parts.push(label);
        } else {
            parts.push(format!("{} {label}", device_short_name(device)));
        }
    }
    parts.push(key_label(&input.key));
    let mut s = parts.join(" + ");
    if input.hold {
        s.push_str(" (hold)");
    }
    s
}

fn by_device(out: &mut String, bindings: &Bindings, report: &Report, ctx: &Ctx<'_>) {
    struct Entry<'a> {
        label: String,
        input: &'a Input,
        action: &'a ActionBinding,
        slot: Slot,
    }
    let mut per_device: FxHashMap<(&str, u32), Vec<Entry<'_>>> = FxHashMap::default();
    for action in &bindings.actions {
        for (slot, input) in action.inputs() {
            per_device
                .entry((input.device.as_str(), input.device_index))
                .or_default()
                .push(Entry {
                    label: label_on_device(input),
                    input,
                    action,
                    slot,
                });
        }
    }

    out.push_str("<section id=\"by-device\">\n<h2>By device</h2>\n<div class=\"grid\">\n");
    for d in &report.devices {
        let Some(entries) = per_device.get_mut(&(d.device.as_str(), d.device_index)) else {
            continue;
        };
        // Letters, digits and named keys first (natural order), punctuation last.
        let punctuation = |label: &str| !label.starts_with(|c: char| c.is_alphanumeric());
        entries.sort_by(|a, b| {
            punctuation(&a.label)
                .cmp(&punctuation(&b.label))
                .then_with(|| natural_cmp(&a.label, &b.label))
                .then_with(|| {
                    catalogue_order(&a.action.action).cmp(&catalogue_order(&b.action.action))
                })
        });

        // One row per distinct input.
        let mut rows: Vec<(String, &Input, bool, Vec<String>)> = Vec::new();
        for e in entries.iter() {
            let info = e.action.info();
            let conflict = ctx.is_conflicted(&e.action.action, e.slot);
            let name = format!(
                "<span{}>{}</span> <span class=\"ctx\">{}</span>",
                if conflict { " class=\"cn\"" } else { "" },
                esc(&info.name),
                info.context.label()
            );
            match rows.last_mut() {
                Some((label, _, c, names)) if *label == e.label => {
                    *c |= conflict;
                    names.push(name);
                }
                _ => rows.push((e.label.clone(), e.input, conflict, vec![name])),
            }
        }

        let kind = if d.kind.label() == d.name {
            String::new()
        } else {
            format!(" <span class=\"ctx\">{}</span>", d.kind.label())
        };
        let _ = writeln!(
            out,
            "<div class=\"card{}\"><h3><span class=\"dot {}\"></span>{}{kind}</h3><div class=\"keys\">",
            if rows.len() > 24 { " span" } else { "" },
            kind_class(d.kind),
            esc(&d.name),
        );
        for (label, input, conflict, names) in rows {
            let _ = writeln!(
                out,
                "<div class=\"kr{}\"><div class=\"kk\">{}</div><div class=\"ka\">{}</div></div>",
                if conflict { " c" } else { "" },
                chip_labelled(input, &label, conflict, None, ""),
                names.join("<br>")
            );
        }
        out.push_str("</div></div>\n");
    }
    out.push_str("</div>\n</section>\n");
}

